function readStoredLocale(): Locale {
  if (typeof window === 'undefined') return 'zh-CN'
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY)
    return stored === 'en-US' || stored === 'zh-CN' ? stored : 'zh-CN'
  } catch {
    return 'zh-CN'
  }
}

locale.value = readStoredLocale()

function persistLocale(value: Locale) {
  if (typeof window !== 'undefined') {
    try {
      window.localStorage.setItem(STORAGE_KEY, value)
    } catch {
      // Language switching should still work when storage is unavailable.
    }
    document.documentElement.lang = value
  }
}

if (typeof document !== 'undefined') document.documentElement.lang = locale.value

export function setLocale(value: Locale) {
  locale.value = value
  persistLocale(value)
}

export type LocaleMessage = string | Record<Locale, string>

export function localeMessage(english: string, chinese: string): Record<Locale, string> {
  return { 'en-US': english, 'zh-CN': chinese }
}

export function resolveLocaleMessage(value: LocaleMessage) {
  return typeof value === 'string' ? value : value[locale.value]
}

export function useLocaleMessage() {
  const value = ref<LocaleMessage>('')
  return computed({
    get: () => resolveLocaleMessage(value.value),
    set: (next: LocaleMessage) => { value.value = next },
  })
}

function translate(language: Locale, key: string, params: Record<string, string | number>) {
  const template = messages[language][key] ?? messages['zh-CN'][key] ?? key
  return template.replace(/\{(\w+)\}/g, (placeholder, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : placeholder)
}

export function useI18n() {
  const currentLocale = computed(() => locale.value)
  function t(key: string, params: Record<string, string | number> = {}) {
    return translate(locale.value, key, params)
  }
  function message(key: string, params: Record<string, string | number> = {}) {
    return localeMessage(translate('en-US', key, params), translate('zh-CN', key, params))
  }
  return { locale: currentLocale, t, message, setLocale }
}
